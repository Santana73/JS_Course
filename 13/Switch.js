let day = 0;

switch(day){
    case 1 :
        console.log('Hj é Domingo');
        break
    case 2 :
        console.log('Hj é Segunda');
        break
    case 3 :
        console.log('Hj é Terça');
        break
    case 4 :
        console.log('Hj é Quarta');
        break
    case 5 :
        console.log('Hj é Quinta');
        break
    case 6 :
        console.log('Hj é Sexta');
        break
    case 7 :
        console.log('Hj é Sabado');
        break
    default :
        console.log(`${day} não é um dia`);
        break


}